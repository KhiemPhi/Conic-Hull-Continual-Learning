#!/usr/bin/env python3
"""make_results.py -- regenerate results.txt from the experiment JSONs.

WHY THIS IS GENERATED AND NOT HAND-WRITTEN
    results.txt is the running record of every measured cell. Cells land days apart, and a
    hand-maintained results file drifts from the JSONs silently -- which is exactly the class
    of bug that produced the mixed legacy/pilot exp55 table (1 pilot seed averaged with 2
    legacy seeds while printing "cells 3"). Everything here is read from disk at generation
    time, filtered to ORDER=pilot, and keyed by (dataset, T, seed) so orders and task counts
    cannot merge.

USAGE
    source ~/venvs/ml_env/bin/activate
    python -u make_results.py            # rewrites results.txt
"""
