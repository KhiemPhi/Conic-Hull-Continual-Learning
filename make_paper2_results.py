#!/usr/bin/env python3
"""make_paper2_results.py -- regenerate results_paper2.txt from the crux_* seed outputs.

WHY THIS IS GENERATED, NOT HAND-WRITTEN
    Same reason as make_results.py: a hand-maintained results file drifts from the arrays on
    disk silently. It also protects against the specific error that was made while reading
    these files by hand on 2026-08-14 -- the crux_transport npz stores a TWO-ELEMENT array
    per variant, (recon_cos, NCM), and averaging across both axes yields a number that is
    neither, looks plausible, and led to a false "Table 1 needs rebuilding" conclusion. The
    unpacking is now written down once, here, with an assert on the shape.

WHAT IT READS  (all produced by the 3-seed chain of 2026-08-14)
    crux_sweep_hist_s{0,1,2}.npz            Result 2, 10-task depth curve
    crux_relational_lam{0,50}_s{0,1,2}.npz  Result 4, Gram-penalty response
    crux_transport_s{0,1,2}.npz             Result 1, transport hypothesis classes
                                            (this is the INDEX-FIXED lam=50 arm; the previous
                                            lam=50 result was invalid -- scrambled Gram
                                            reference rows -- and was never reported)

RIGIDITY IS A DERIVED QUANTITY, NOT A STORED ONE
    The npz stores `rigid_deg` = the residual drift angle left after removing one global
    rotation. The number the paper quotes is
        rigidity% = 100 * (1 - rigid_deg / eps)
    exactly as crux_sweep.py:185 and crux_relational.py:199 print it. Reading `rigid_deg`
    as if it were the percentage understates rigidity by ~70 points.

USAGE
    source ~/venvs/ml_env/bin/activate
    python -u make_paper2_results.py          # rewrites results_paper2.txt
"""
import io
import os

import numpy as np

REPO = os.path.dirname(os.path.abspath(__file__))
SEEDS = [0, 1, 2]
OUT = os.path.join(REPO, "results_paper2.txt")


def ms(vals):
    v = np.asarray(vals, float)
    return v.mean(), (v.std(ddof=1) if len(v) > 1 else float("nan"))


def f(m, s, w=7, p=3):
    return f"{m:>{w}.{p}f}±{s:<5.{p}f}" if s == s else f"{m:>{w}.{p}f}{'':<6}"


def rigidity(eps, rigid_deg):
    """The percentage the papers quote -- see the module docstring.

    UNDEFINED before the backbone has adapted. At t=0 the measured eps is 0.007-0.012 deg
    and rigid_deg is 0-0.006 deg -- both pure numerical noise -- so the ratio is noise/noise.
    The scripts' inline `max(eps, 1e-6)` guard turns that into an arbitrary finite number
    (it printed 71.6% here), which is worse than a gap because it looks like a measurement.
    The threshold is 1 deg because the regimes are cleanly separated: t=0 sits at ~0.01 deg
    and t=1 already at ~25 deg, so nothing real is ever suppressed."""
    if eps < 1.0:
        return float("nan")
    return 100.0 * (1.0 - rigid_deg / eps)


def main():
    o = io.StringIO()
    W = 100
    o.write("=" * W + "\n")
    o.write("PAPER 2 RESULTS -- representation drift under PEFT as a gauge rotation\n")
    o.write("CIFAR-100, vit_base_patch16_224.augreg2_in21k_ft_in1k, shared LoRA r32, "
            "3 seeds (0,1,2).\n")
    o.write("GENERATED by make_paper2_results.py from the crux_* npz files -- do not hand-edit.\n")
    o.write("=" * W + "\n")

    # ---------------------------------------------------------------- Result 2
    S = [np.load(os.path.join(REPO, f"crux_sweep_hist_s{s}.npz")) for s in SEEDS]
    n_t = len(S[0]["eps"])
    o.write("\n1. RESULT 2 -- ONE PROCRUSTES MAP SUFFICES, TO DEPTH (task-0 cohort)\n")
    o.write("-" * W + "\n")
    o.write(f"  {'t':>3}{'eps(deg)':>10}{'rigidity%':>11}{'gram':>8}"
            f"{'stale':>15}{'transport':>15}{'oracle':>15}{'tr-orac':>9}\n")
    for t in range(n_t):
        e = ms([z["eps"][t] for z in S])
        rg = ms([rigidity(z["eps"][t], z["rigid_deg"][t]) for z in S])
        g = ms([z["gram_corr"][t] for z in S])
        st = ms([z["coh_stale"][t] for z in S])
        tr = ms([z["coh_transport"][t] for z in S])
        oc = ms([z["coh_oracle"][t] for z in S])
        rgs = f"{rg[0]:>11.1f}" if rg[0] == rg[0] else f"{'n/a':>11}"
        o.write(f"  {t:>3}{e[0]:>10.1f}{rgs}{g[0]:>8.2f}"
                f"{f(st[0], st[1])}{f(tr[0], tr[1])}{f(oc[0], oc[1])}{tr[0]-oc[0]:>+9.3f}\n")
    d = [abs(np.mean([z["coh_transport"][t] for z in S])
             - np.mean([z["coh_oracle"][t] for z in S])) for t in range(n_t)]
    o.write(f"\n  |transport - oracle| <= {max(d):.3f} at EVERY depth. A single orthogonal\n"
            f"  Procrustes map applied to stale prototypes tracks an oracle that refits them\n"
            f"  in the current frame, while uncorrected prototypes decay to "
            f"{np.mean([z['coh_stale'][-1] for z in S]):.3f}.\n")
    o.write(f"  eps SATURATES: {np.mean([z['eps'][1] for z in S]):.1f} -> "
            f"{np.mean([z['eps'][n_t//2] for z in S]):.1f} -> "
            f"{np.mean([z['eps'][-1] for z in S]):.1f} deg. The drift explores a BOUNDED orbit.\n")

    o.write("\n  SEEN-way (all classes) -- what the gauge story does NOT fix\n")
    o.write(f"  {'t':>3}{'frozen':>10}{'stale':>10}{'oracle':>10}{'orac-froz':>12}\n")
    for t in [0, 2, 4, 7, n_t - 1]:
        fr = ms([z["seen_frozen"][t] for z in S])
        st = ms([z["seen_stale"][t] for z in S])
        oc = ms([z["seen_oracle"][t] for z in S])
        o.write(f"  {t:>3}{fr[0]:>10.3f}{st[0]:>10.3f}{oc[0]:>10.3f}{oc[0]-fr[0]:>+12.3f}\n")
    o.write("  Stale COLLAPSES (gauge artifact, repairable). But the ORACLE also falls below\n"
            "  frozen from t2 on and the gap widens -- representational degradation, which no\n"
            "  prototype geometry can recover. This is what Result 4 addresses.\n")

    # ---------------------------------------------------------------- Result 4
    o.write("\n2. RESULT 4 -- THE INVARIANT PRESCRIBES THE LOSS (Gram penalty, 100-way final)\n")
    o.write("-" * W + "\n")
    R = {l: [np.load(os.path.join(REPO, f"crux_relational_lam{l}_s{s}.npz")) for s in SEEDS]
         for l in (0, 50)}
    o.write(f"  {'metric':<22}{'lambda=0':>16}{'lambda=50':>16}{'delta':>10}\n")
    rows = [("oracle (feature quality)", "seen_oracle"), ("stale prototypes", "seen_stale"),
            ("transported prototypes", "seen_transport"), ("new-task accuracy", "new_acc"),
            ("gram correlation", "gram_corr"), ("eps (deg)", "eps")]
    for lbl, k in rows:
        a = ms([z[k][-1] for z in R[0]])
        b = ms([z[k][-1] for z in R[50]])
        o.write(f"  {lbl:<22}{f(a[0], a[1])}{f(b[0], b[1])}{b[0]-a[0]:>+10.3f}\n")
    ra = ms([rigidity(z["eps"][-1], z["rigid_deg"][-1]) for z in R[0]])
    rb = ms([rigidity(z["eps"][-1], z["rigid_deg"][-1]) for z in R[50]])
    o.write(f"  {'rigidity%':<22}{f(ra[0], ra[1], p=1)}{f(rb[0], rb[1], p=1)}"
            f"{rb[0]-ra[0]:>+10.1f}\n")
    fr = np.mean([z["seen_frozen"][-1] for z in R[0]])
    o.write(f"  {'frozen backbone':<22}{fr:>7.3f}{'':<6}{fr:>7.3f}\n")
    ob = ms([z["seen_oracle"][-1] for z in R[50]])
    o.write(f"\n  Rotations leave the Gram matrix unchanged, so the penalty is FLAT along the\n"
            f"  gauge orbit and steep orthogonal to it: it permits the harmless motion and\n"
            f"  forbids the distortion. Drift is measurably more rigid ({ra[0]:.0f}% -> {rb[0]:.0f}%),\n"
            f"  and the feature-quality ceiling crosses frozen ({fr:.3f}).\n")
    o.write(f"  HONEST CEILING: {ob[0]:.3f} vs frozen {fr:.3f} is a TIE (+{ob[0]-fr:.3f}), not a win.\n"
            f"  This backbone is near its ceiling on CIFAR-100; a win needs a benchmark with\n"
            f"  adaptation headroom, which has NOT been run.\n")
    o.write(f"  NEW AT 3 SEEDS: the penalty also removes seed variance -- oracle sd "
            f"{ms([z['seen_oracle'][-1] for z in R[0]])[1]:.3f} -> {ob[1]:.3f}.\n")

    # ---------------------------------------------------------------- Result 1
    o.write("\n3. RESULT 1 -- THE DRIFT IS AFFINE, AND MOSTLY A ROTATION (single step, 50/50)\n")
    o.write("-" * W + "\n")
    T = [np.load(os.path.join(REPO, f"crux_transport_s{s}.npz")) for s in SEEDS]
    probe = T[0]["lam=0|identity"]
    assert np.shape(probe) == (2,), (
        f"crux_transport stores (recon_cos, NCM) PAIRS, got shape {np.shape(probe)}. "
        f"Averaging across both axes yields a number that is neither -- the error made on "
        f"2026-08-14 that produced a spurious 'identity 0.774'.")
    o.write(f"  {'lambda':<8}{'transport class':<14}{'recon cos to phi_0':>22}"
            f"{'old-class NCM':>20}\n")
    for lam in ("lam=0", "lam=50"):
        for v in ("identity", "orthogonal", "linear", "mlp"):
            a = np.array([t[f"{lam}|{v}"] for t in T], float)
            rc, nc = ms(a[:, 0]), ms(a[:, 1])
            o.write(f"  {lam:<8}{v:<14}{f(rc[0], rc[1], w=13, p=4)}"
                    f"{f(nc[0], nc[1], w=11, p=4)}\n")
    frz = np.mean([float(t["frozen"]) for t in T])
    o.write(f"  {'--':<8}{'frozen':<14}{'--':>22}{frz:>17.4f}\n")
    ln = np.mean([t["lam=0|linear"][0] for t in T])
    mp = np.mean([t["lam=0|mlp"][0] for t in T])
    idn = np.mean([t["lam=0|identity"][0] for t in T])
    o.write(f"\n  MLP adds {mp-ln:+.4f} recon cos over a LINEAR map and is WORSE in accuracy\n"
            f"  => the drift is AFFINE at this measurement budget; mapping back is one matrix.\n"
            f"  identity recon cos {idn:.4f} = cos({np.degrees(np.arccos(idn)):.1f} deg), which\n"
            f"  independently reproduces the eps measured by crux_drift on a separate protocol.\n"
            f"  Every transport class exceeds frozen ({frz:.4f}) on DECISIONS while feature\n"
            f"  recovery floors near 0.87 => the unrecovered component is class-irrelevant.\n")
    o.write("  NOTE the lam=50 block is the INDEX-FIXED rerun (2026-08-14). The previous\n"
            "  lam=50 arm used a scrambled Gram reference (983/1000 rows wrong) and was never\n"
            "  reported; these are the first valid numbers for it.\n")

    o.write("\n" + "-" * W + "\n")
    o.write("""CAVEATS THAT MUST TRAVEL WITH THESE NUMBERS
  - One dataset (CIFAR-100), one backbone. Nothing here is tested off augreg2_in21k_ft_in1k.
  - "MLP ~ linear" is NOT proof of absent nonlinear structure: ~1e4 pairs against a 5.7M-param
    MLP is underpowered. The honest claim is no DETECTABLE nonlinear gain at this budget.
  - crux_recovered (Result 3, the frame-offset decomposition) is log-only; its accuracy columns
    build prototypes from test features (~1% self-inclusion) and are mildly optimistic. The
    structural metrics that carry the argument -- angles, %systematic, CKA, Gram -- involve no
    classification and are unaffected.
  - Prototypes use 128/class; replay is 20/class.
""")
    o.write("=" * W + "\n")

    open(OUT, "w").write(o.getvalue())
    print(o.getvalue())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
